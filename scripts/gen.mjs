#!/usr/bin/env bun
// Generates every wire type from schema/*.json (build spec §2.1). Nothing else defines a wire shape.
//   gen/ts/protocol.ts            TS types, enum value lists, the event union, tool names
//   gen/ts/schemas.json           one bundled JSON Schema document for ajv in the Worker
//   gen/ts/tools.json             MCP tool definitions with input/output schemas fully inlined
//   daemon/internal/protocol/gen.go   Go structs, enums, required-key checks, event decode
// Deterministic: same schema in, same bytes out. `make gen` runs gofmt on the Go file afterwards.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SCHEMA_DIR = path.join(ROOT, 'schema');
const FILES = ['common', 'tokens', 'task', 'message', 'events', 'pod-api', 'tools'];
const BANNED = ['oneOf', 'anyOf', 'allOf', 'not', 'if', 'then', 'else', 'patternProperties', '$dynamicRef'];
const HEADER = 'Code generated by scripts/gen.mjs from schema/. DO NOT EDIT.';

// ---------- load and index ----------
const docs = Object.fromEntries(FILES.map((f) => [f, JSON.parse(fs.readFileSync(path.join(SCHEMA_DIR, `${f}.json`), 'utf8'))]));
const defs = new Map(); // name -> { file, schema }
for (const f of FILES) {
  for (const [name, schema] of Object.entries(docs[f].$defs || {})) {
    if (defs.has(name)) fail(`duplicate def ${name} in ${f}.json and ${defs.get(name).file}.json; def names are global`);
    defs.set(name, { file: f, schema });
  }
}

function fail(msg) { console.error(`gen: ${msg}`); process.exit(1); }

function refName(ref, fromFile) {
  const m = /^(?:([a-z-]+)\.json)?#\/\$defs\/([A-Za-z0-9]+)$/.exec(ref);
  if (!m) fail(`unsupported $ref ${ref} in ${fromFile}.json`);
  const name = m[2];
  const d = defs.get(name);
  if (!d) fail(`$ref ${ref} in ${fromFile}.json points at no def`);
  if ((m[1] || fromFile) !== d.file) fail(`$ref ${ref} in ${fromFile}.json names the wrong file (${name} lives in ${d.file}.json)`);
  return name;
}

// Reject composition keywords and inline objects anywhere below a def.
function check(node, where, depth) {
  if (Array.isArray(node)) { node.forEach((n, i) => check(n, `${where}[${i}]`, depth)); return; }
  if (!node || typeof node !== 'object') return;
  for (const k of BANNED) if (k in node) fail(`${where} uses ${k}; the schema allows no composition (go-jsonschema can't, spec §2.1)`);
  if (node.$ref) refName(node.$ref, where.split('.json')[0]);
  if (depth > 0 && node.type === 'object' && node.properties) fail(`${where} is an inline object; make it a named $def`);
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('x-') || k === 'enum' || k === 'const' || k === 'required') continue;
    if (k === 'properties') { for (const [p, s] of Object.entries(v)) check(s, `${where}.${p}`, depth + 1); continue; }
    check(v, `${where}.${k}`, depth + 1);
  }
}
for (const [name, { file, schema }] of defs) check(schema, `${file}.json#${name}`, 0);

// x-variants must cover EventType exactly.
const variants = docs.events['x-variants'];
const eventTypes = defs.get('EventType').schema.enum;
for (const t of eventTypes) if (!variants[t]) fail(`EventType ${t} has no x-variants entry`);
for (const t of Object.keys(variants)) if (!eventTypes.includes(t)) fail(`x-variants ${t} is not in EventType`);
const variantData = Object.fromEntries(Object.entries(variants).map(([t, v]) => [t, refName(v.data.includes('#') ? v.data : `#/$defs/${v.data}`, 'events')]));
const tools = docs.tools['x-tools'].map((t) => ({
  ...t,
  inputDef: refName(t.input.includes('#') ? t.input : `#/$defs/${t.input}`, 'tools'),
  outputDef: refName(t.output.includes('#') ? t.output : `#/$defs/${t.output}`, 'tools'),
}));

const kindOf = (s) => (s.enum ? 'enum' : s.type);
const ordered = [...defs.entries()];

// ---------- TypeScript ----------
function tsType(s, file) {
  if (s.$ref) return refName(s.$ref, file);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
  switch (s.type) {
    case 'string': return 'string';
    case 'integer': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'array': return `${wrapTs(tsType(s.items, file))}[]`;
    case 'object': return 'Record<string, unknown>';
    default: fail(`no TS mapping for ${JSON.stringify(s)}`);
  }
}
const wrapTs = (t) => (t.includes('|') ? `(${t})` : t);
const doc = (s, indent = '') => (s.description ? `${indent}/** ${s.description.replace(/\*\//g, '*\\/')} */\n` : '');
const tsKey = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k));

let ts = `// ${HEADER}\n/* eslint-disable */\n\n`;
for (const [name, { file, schema: s }] of ordered) {
  ts += doc(s);
  if (s.type === 'object' && s.properties) {
    const req = new Set(s.required || []);
    ts += `export interface ${name} {\n`;
    for (const [k, p] of Object.entries(s.properties)) ts += doc(p, '  ') + `  ${tsKey(k)}${req.has(k) ? '' : '?'}: ${tsType(p, file)};\n`;
    ts += '}\n';
  } else if (s.type === 'object') {
    ts += `export type ${name} = Record<string, never>;\n`;
  } else {
    ts += `export type ${name} = ${tsType(s, file)};\n`;
    if (s.enum) ts += `export const ${name}Values = ${JSON.stringify(s.enum)} as const;\n`;
  }
  ts += '\n';
}
ts += `/** Which data definition each event type carries (events.json x-variants). */\nexport interface EventDataMap {\n`;
for (const t of eventTypes) ts += `  ${JSON.stringify(t)}: ${variantData[t]};\n`;
ts += `}\n\nexport type EventOf<T extends EventType> = Omit<Envelope, 'type' | 'data'> & { type: T; data: EventDataMap[T] };\n`;
ts += `export type AnyEvent = { [K in EventType]: EventOf<K> }[EventType];\n\n`;
ts += `export const EVENT_DIRECTION = {\n${eventTypes.map((t) => `  ${JSON.stringify(t)}: ${JSON.stringify(variants[t].dir)},`).join('\n')}\n} as const;\n\n`;
ts += `export const EVENT_DATA_DEF = {\n${eventTypes.map((t) => `  ${JSON.stringify(t)}: ${JSON.stringify(variantData[t])},`).join('\n')}\n} as const;\n\n`;
ts += `export interface ToolIO {\n${tools.map((t) => `  ${t.name}: { input: ${t.inputDef}; output: ${t.outputDef} };`).join('\n')}\n}\n`;
ts += `export type ToolName = keyof ToolIO;\nexport const TOOL_NAMES = ${JSON.stringify(tools.map((t) => t.name))} as const;\n`;

// ---------- bundled JSON Schema (ajv) ----------
function rewriteRefs(node, file) {
  if (Array.isArray(node)) return node.map((n) => rewriteRefs(n, file));
  if (!node || typeof node !== 'object') return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('x-')) continue;
    out[k] = k === '$ref' ? `#/$defs/${refName(v, file)}` : rewriteRefs(v, file);
  }
  return out;
}
const bundle = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: 'https://commonly.me/v4/schema/bundle.json',
  $comment: HEADER,
  $defs: Object.fromEntries(ordered.map(([name, { file, schema }]) => [name, rewriteRefs(schema, file)])),
};

// ---------- MCP tools, refs inlined ----------
function inline(node, file, seen = []) {
  if (Array.isArray(node)) return node.map((n) => inline(n, file, seen));
  if (!node || typeof node !== 'object') return node;
  if (node.$ref) {
    const name = refName(node.$ref, file);
    if (seen.includes(name)) fail(`recursive $ref through ${seen.join(' -> ')} -> ${name}`);
    const { file: f, schema } = defs.get(name);
    const { $ref, ...rest } = node; // keep a sibling description if one is set
    return { ...inline(schema, f, [...seen, name]), ...inline(rest, file, seen) };
  }
  const out = {};
  for (const [k, v] of Object.entries(node)) if (!k.startsWith('x-')) out[k] = inline(v, file, seen);
  return out;
}
const mcpTools = tools.map((t) => {
  const inputSchema = inline({ $ref: `#/$defs/${t.inputDef}` }, defs.get(t.inputDef).file);
  const outputSchema = inline({ $ref: `#/$defs/${t.outputDef}` }, defs.get(t.outputDef).file);
  if (inputSchema.type !== 'object' || outputSchema.type !== 'object') fail(`tool ${t.name}: MCP input and output schemas must be objects`);
  return { name: t.name, description: t.description, inputSchema, outputSchema };
});

// ---------- Go ----------
const INITIALISMS = new Set(['id', 'url', 'uri', 'mcp', 'os', 'acp', 'http', 'json', 'api', 'ui']);
const words = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^A-Za-z0-9]+/).filter(Boolean);
const goIdent = (s) => words(s).map((w) => (INITIALISMS.has(w.toLowerCase()) ? w.toUpperCase() : w[0].toUpperCase() + w.slice(1))).join('');
const goDef = (name) => goIdent(name);

function goType(s, file) {
  if (s.$ref) return goDef(refName(s.$ref, file));
  if (s.enum || s.const !== undefined) {
    if (s.const !== undefined && Number.isInteger(s.const)) return 'int64';
    return 'string';
  }
  switch (s.type) {
    case 'string': return 'string';
    case 'integer': return 'int64';
    case 'number': return 'float64';
    case 'boolean': return 'bool';
    case 'array': return `[]${goType(s.items, file)}`;
    case 'object': return 'json.RawMessage';
    default: fail(`no Go mapping for ${JSON.stringify(s)}`);
  }
}
const goComment = (s, indent = '') => (s.description ? s.description.split('\n').map((l) => `${indent}// ${l}`).join('\n') + '\n' : '');

let go = `// ${HEADER}\n\npackage protocol\n\nimport (\n\t"encoding/json"\n\t"fmt"\n)\n\n`;
for (const [name, { file, schema: s }] of ordered) {
  const g = goDef(name);
  go += goComment(s);
  if (s.type === 'object' && s.properties) {
    const req = s.required || [];
    go += `type ${g} struct {\n`;
    for (const [k, p] of Object.entries(s.properties)) {
      let t = goType(p, file);
      const optional = !req.includes(k);
      if (optional && !t.startsWith('[]') && t !== 'json.RawMessage') t = `*${t}`;
      go += goComment(p, '\t') + `\t${goIdent(k)} ${t} \`json:"${k}${optional ? ',omitempty' : ''}"\`\n`;
    }
    go += '}\n\n';
    go += `// UnmarshalJSON rejects input that lacks a required key.\nfunc (x *${g}) UnmarshalJSON(b []byte) error {\n`;
    if (req.length) {
      go += `\tvar keys map[string]json.RawMessage\n\tif err := json.Unmarshal(b, &keys); err != nil {\n\t\treturn err\n\t}\n`;
      go += `\tfor _, k := range []string{${req.map((r) => JSON.stringify(r)).join(', ')}} {\n\t\tif _, ok := keys[k]; !ok {\n\t\t\treturn fmt.Errorf("${name}: missing required field %q", k)\n\t\t}\n\t}\n`;
    }
    go += `\ttype plain ${g}\n\treturn json.Unmarshal(b, (*plain)(x))\n}\n\n`;
  } else if (s.type === 'object') {
    go += `type ${g} struct{}\n\n`;
  } else if (s.enum) {
    go += `type ${g} string\n\nconst (\n`;
    for (const v of s.enum) go += `\t${g}${goIdent(String(v)) || 'Empty'} ${g} = ${JSON.stringify(v)}\n`;
    go += ')\n\n';
    go += `// Valid reports whether x is one of the schema's values.\nfunc (x ${g}) Valid() bool {\n\tswitch x {\n\tcase ${s.enum.map((v) => `${g}${goIdent(String(v))}`).join(', ')}:\n\t\treturn true\n\t}\n\treturn false\n}\n\n`;
  } else {
    go += `type ${g} = ${goType(s, file)}\n\n`;
  }
}
go += `// Registry returns a fresh value for each object definition, by schema name. Tests and decoders use it.\nvar Registry = map[string]func() any{\n`;
for (const [name, { schema: s }] of ordered) if (s.type === 'object') go += `\t${JSON.stringify(name)}: func() any { return new(${goDef(name)}) },\n`;
go += '}\n\n';
go += `// EventDirection is who sends each event type: s2c, c2s or local (daemon to TUI only).\nvar EventDirection = map[EventType]string{\n`;
for (const t of eventTypes) go += `\tEventType${goIdent(t)}: ${JSON.stringify(variants[t].dir)},\n`;
go += '}\n\n';
go += `// DecodeEventData decodes an envelope's data into the type x-variants names for its event type.\nfunc DecodeEventData(t EventType, raw json.RawMessage) (any, error) {\n\tswitch t {\n`;
for (const t of eventTypes) go += `\tcase EventType${goIdent(t)}:\n\t\tvar v ${goDef(variantData[t])}\n\t\tif err := json.Unmarshal(raw, &v); err != nil {\n\t\t\treturn nil, fmt.Errorf("%s: %w", t, err)\n\t\t}\n\t\treturn &v, nil\n`;
go += `\t}\n\treturn nil, fmt.Errorf("unknown event type %q", t)\n}\n\n`;
go += `// ToolNames lists the MCP tools in schema order.\nvar ToolNames = []string{${tools.map((t) => JSON.stringify(t.name)).join(', ')}}\n`;

// ---------- write ----------
const write = (rel, content) => {
  const p = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
};
write('gen/ts/protocol.ts', ts);
write('gen/ts/schemas.json', JSON.stringify(bundle, null, 2) + '\n');
write('gen/ts/tools.json', JSON.stringify({ $comment: HEADER, tools: mcpTools }, null, 2) + '\n');
write('daemon/internal/protocol/gen.go', go);
console.log(`gen: ${defs.size} defs, ${eventTypes.length} event types, ${tools.length} tools`);
